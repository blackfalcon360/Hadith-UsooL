    public static Node get(String id) { return N.get(id); }

    /** self-check used by the tests: every option points to an existing node */
    public static List<String> brokenLinks() {
        List<String> bad = new ArrayList<>();
        for (Node n : N.values()) for (Opt o : n.opts) if (!N.containsKey(o.next)) bad.add(n.id + " -> " + o.next);
        return bad;
    }
